export function t(lang: Lang, key: string, vars?: Record<string, string>): string {
  const raw = UI[lang][key] ?? UI.fr[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

